"""Generate the Part B data-sources catalogue.

Reads registry/geospatial_sources.yaml (machine facts) and docs/tools/source_supplements.yaml (hand-authored
context) and writes docs/geospatial/data-sources/index.md plus one page per registered source.

Hand-written pages in that folder (controlled-inputs.md, update-procedures.md) are not touched.

Run from the repository root:  python docs/tools/gen_sources.py
"""
from pathlib import Path

import yaml

root = Path(__file__).resolve().parents[2]
docs = root / "docs"
out_dir = docs / "geospatial" / "data-sources"
proc_dir = docs / "geospatial" / "data-processing"
out_dir.mkdir(parents=True, exist_ok=True)

registry = yaml.safe_load((root / "registry" / "geospatial_sources.yaml").read_text(encoding="utf-8"))
supp = yaml.safe_load((docs / "tools" / "source_supplements.yaml").read_text(encoding="utf-8"))

# Build-profile keys that govern each source.
CONFIG_KEYS = {
    "nrcan_land_cover_2020": "`[renewables.land_exclusion]` via the selected renewables settings",
    "eccc_cpcad_2025": "`[renewables.land_exclusion]` via the selected renewables settings",
    "nrcan_wind_turbines_snapshot_20261023": "Bronze inventory only; not yet consumed by Silver",
    "transitionzero_solar_2024q1": "Bronze inventory only; not yet consumed by Silver",
    "statcan_2021_province_territory_boundaries": "`[study_area]`, `[basemaps]`",
    "statcan_2021_da_population_density_inputs": "`[pipeline_impedance]`, `[gasoline_demand.proxies]`",
    "statcan_gasoline_demand_inputs": "`[gasoline_demand]` (`sales_year`, `gasoline_density_t_per_litre`, `proxies.*`)",
    "nrcan_aboriginal_lands_national_en": "`[pipeline_impedance]` (`penalty_profile`)",
    "statcan_nrn_national_bilingual": "`[roads]`, `[roads.classes]`, `[road_connectivity]`",
    "nrcan_nhn_hhyd_national_en": "`[hydrography]`, `[hydrography.polygons]`, `[hydrography.lines]`",
    "eccc_large_facility_ghg_2024": "`registry/model.toml` `[emissions]`",
    "canco2_unified_storage_selected_release": "`[storage]`; scenario `[storage]`",
    "copernicus_era5_canada_2018_renewables": "`[renewables]` and its selected renewables settings",
    "atb_electricity_2025_v1": "`[renewables]`; `config/atb/*.toml`; `config/renewables/*.toml`",
}


def chapters() -> dict[int, tuple[str, str]]:
    found = {}
    for path in sorted(proc_dir.glob("[0-9][0-9]-*.md")):
        title = path.read_text(encoding="utf-8").splitlines()[0].lstrip("# ").strip()
        found[int(path.name[:2])] = (path.name, title)
    return found


CH = chapters()


def chapter_links(numbers, prefix="../data-processing/"):
    return ", ".join(f"[{CH[n][1]}]({prefix}{CH[n][0]})" for n in numbers if n in CH)


def one_line(text):
    return " ".join(str(text).split())


sources = registry["sources"]
summary = [
    "# Data Sources Catalogue",
    "",
    "Part B of the geospatial documentation. Each profile gives the origin, the fields the model uses, where they are used, "
    "how to update the source and how to cite it. Processing logic is in [Part A: Data Processing](../data-processing/01-overview-and-architecture.md).",
    "",
    "> Generated by `docs/tools/gen_sources.py` from `registry/geospatial_sources.yaml` and `docs/tools/source_supplements.yaml`. "
    "Do not edit the generated pages by hand.",
    "",
    "## 1. Data source summary",
    "",
    "| # | Source | Publisher | Licence | Release model | Refresh | Used in |",
    "|---|---|---|---|---|---|---|",
]
for index, source in enumerate(sources, start=2):
    extra = supp[source["id"]]
    acquisition = source.get("acquisition", {})
    used = ", ".join(f"{n}" for n in extra["used_in"])
    summary.append(
        f"| {index} | [{source.get('title', source['id'])}]({extra['slug']}.md) | {source.get('publisher', '')} | {source.get('licence', '')} "
        f"| {acquisition.get('release_model', '')} | {acquisition.get('refresh_policy', '')} | ch. {used} |"
    )
n_controlled = len(sources) + 2
summary += [
    f"| {n_controlled} | [Controlled project inputs](controlled-inputs.md) | Project | n/a | Versioned in repository | Manual | ch. 8, 9, 10, 12 |",
    f"| {n_controlled + 1} | [Update procedures](update-procedures.md) | | | | | |",
    "",
    "Release models: *fixed* sources do not change; *rolling* sources serve the current release at a stable URL, so a later download "
    "may differ. Record the retrieval date for every rolling source.",
    "",
]
(out_dir / "index.md").write_text("\n".join(summary), encoding="utf-8")

for index, source in enumerate(sources, start=2):
    extra = supp[source["id"]]
    acquisition = source.get("acquisition", {})
    bronze = source.get("bronze", {})
    lines = [
        f"# {index}. {source.get('title', source['id'])}",
        "",
        "> Generated by `docs/tools/gen_sources.py`. Do not edit by hand.",
        "",
        "## Description",
        "",
        one_line(extra["description"]),
        "",
        f"- **Registry ID:** `{source['id']}`",
        f"- **Publisher:** {source.get('publisher', '')}",
        f"- **Licence:** {source.get('licence', '')}",
        f"- **Domain / kind:** {source.get('domain', '')} / {source.get('kind', '')}",
        "",
        "## URLs",
        "",
    ]
    for key, value in source.items():
        if key.endswith("_url") and value:
            lines.append(f"- {key.replace('_url', '').replace('_', ' ').capitalize()}: {value}")
    lines += ["", "## Bronze artifacts", "", f"Acquisition module: `{acquisition.get('module', '')}`. Raw location: `{bronze.get('root', '')}`.", ""]
    artifacts = bronze.get("artifacts", {})
    if artifacts:
        lines += ["| Artifact | Path or pattern | Format | Source CRS |", "|---|---|---|---|"]
        for name, artifact in artifacts.items():
            location = artifact.get("path") or artifact.get("glob") or ""
            lines.append(f"| `{name}` | `{location}` | {artifact.get('format', '')} | {artifact.get('source_crs', '')} |")
        lines.append("")
    lines += [
        "## Fields consumed",
        "",
        one_line(extra["fields"]),
        "",
        "## Configuration",
        "",
        CONFIG_KEYS.get(source["id"], ""),
        "",
        "## Used in",
        "",
        f"Chapters: {chapter_links(extra['used_in'])}.",
        "",
        "Silver stages: " + ", ".join(extra["silver_stages"]) + ".",
        "",
        "## Update schedule",
        "",
        f"- Refresh policy: `{acquisition.get('refresh_policy', '')}`",
        f"- Release model: `{acquisition.get('release_model', '')}`",
        "",
        "## How to update",
        "",
        one_line(extra["update"]),
        "",
        "See also [update procedures](update-procedures.md).",
        "",
        "## Citation",
        "",
        one_line(extra["citation"]),
        "",
    ]
    if extra.get("notes"):
        lines += ["## Notes", "", one_line(extra["notes"]), ""]
    (out_dir / f"{extra['slug']}.md").write_text("\n".join(lines), encoding="utf-8")

print(f"wrote {len(sources) + 1} pages to {out_dir.relative_to(root)}")
