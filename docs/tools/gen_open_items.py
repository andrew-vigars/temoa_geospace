"""Generate docs/open-items.md: every [confirm]/[cite-*]/[stale] marker, grouped by chapter.

Run from the repository root:  python docs/tools/gen_open_items.py
"""
import re
from pathlib import Path

docs = Path(__file__).resolve().parents[1]
TAGS = ["confirm", "cite-method", "cite-gis", "cite-data", "stale"]
pat = re.compile(r"\*\*\[(confirm|cite-method|cite-gis|cite-data|stale)\]\*\*")
skip = {"index.md"}
rows, counts = [], {}
pages = sorted((docs / "geospatial" / "data-processing").glob("[0-9]*.md")) + sorted((docs / "geospatial" / "data-sources").glob("*.md"))
for f in pages:
    if f.name in skip:
        continue
    rel = f.relative_to(docs).as_posix()
    title = f.read_text(encoding="utf-8").splitlines()[0].lstrip("# ").strip()
    for n, line in enumerate(f.read_text(encoding="utf-8").splitlines(), 1):
        tags = pat.findall(line)
        if not tags or line.startswith(">"):
            continue
        for t in set(tags):
            counts[(rel, t)] = counts.get((rel, t), 0) + 1
        line = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"", line)
        text = pat.sub(lambda m: f"`{m.group(1)}`", line).strip().strip("|").strip()
        rows.append((rel, title, n, sorted(set(tags)), text[:260]))
out = ["# Open items", "", "> Generated by `docs/tools/gen_open_items.py`. Do not edit by hand.", "",
       "## Counts", "", "| Chapter | " + " | ".join(TAGS) + " |", "|---|" + "---|" * len(TAGS)]
for f in sorted({r[0] for r in rows}):
    title = next(r[1] for r in rows if r[0] == f)
    out.append(f"| [{title}]({f}) | " + " | ".join(str(counts.get((f, t), 0)) for t in TAGS) + " |")
out.append("")
for tag in TAGS:
    out += [f"## `{tag}`", ""]
    for f, title, n, tags, text in rows:
        if tag in tags:
            out.append(f"- [{title}]({f}) (line {n}): {text}")
    out.append("")
(docs / "open-items.md").write_text("\n".join(out), encoding="utf-8")
print(f"{len(rows)} tagged lines")
